describe("ceremonial headlines", () => {
  it("recognises meetings, visits, openings and reports", () => {
    for (const t of CEREMONIAL) assert.ok(isCeremonial(t), t);
  });

  it("keeps decisions, money and laws", () => {
    for (const t of NEWS) assert.ok(!isCeremonial(t), t);
  });

  it("caps only ceremonial scores and keeps null", () => {
    assert.equal(capImportance(CEREMONIAL[0], 85), CEREMONY_MAX);
    assert.equal(capImportance(CEREMONIAL[0], 10), 10);
    assert.equal(capImportance(NEWS[0], 90), 90);
    assert.equal(capImportance(CEREMONIAL[0], null), null);
  });

  it("never lets a digest open with a ceremony", () => {
    const items = [{ title: CEREMONIAL[0] }, { title: NEWS[5] }, { title: CEREMONIAL[1] }, { title: NEWS[0] }];
    assert.deepEqual(
      leadWithNews(items).map((i) => i.title),
      [NEWS[5], NEWS[0], CEREMONIAL[0], CEREMONIAL[1]],
    );
    const only = [{ title: CEREMONIAL[2] }, { title: CEREMONIAL[3] }];
    assert.deepEqual(leadWithNews(only), only);
  });
});
